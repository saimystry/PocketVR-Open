#!/usr/bin/env python3
"""Generate defaults and embedded catalog from the single settings schema."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
schema = json.loads((root / "config/settings.schema.json").read_text(encoding="utf-8"))
defaults = {section: {key: value["default"] for key, value in group["properties"].items()} for section, group in schema["properties"].items()}
flat = {f"{section}.{key}": value for section, group in defaults.items() for key, value in group.items()}
flat["enable"] = True
compact = json.dumps(schema, separators=(",", ":"))
default_text = json.dumps(defaults, indent=2) + "\n"
header = '// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/generate_settings.py; edit config/settings.schema.json.\n#pragma once\n#include <string_view>\nnamespace pocketvr::generated {\ninline constexpr std::string_view settings_schema=R"pvr(' + compact + ')pvr";\ninline constexpr std::string_view defaults=R"pvr(' + json.dumps(defaults, separators=(",", ":")) + ')pvr";\n}\n'
outputs = {"config/pocketvr.json": default_text, "pc/driver/resources/settings/default.vrsettings": json.dumps({"driver_pocketvr": flat}, indent=2) + "\n", "pc/common/include/pocketvr/generated_settings.hpp": header}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for name, text in outputs.items():
    path = root / name
    if args.check:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            raise SystemExit("Generated settings are out of date: " + name)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
print("Settings catalog/defaults " + ("verified." if args.check else "generated."))
